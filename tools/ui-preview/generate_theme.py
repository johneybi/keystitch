"""Generate QML from the reviewed Figma token snapshot; never modify app settings."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def generate():
    tokens = json.loads((ROOT / "design/tokens.json").read_text())
    lines = ["// Generated by generate_theme.py from design/tokens.json.",
             "pragma Singleton", "import QtQuick 2.15", "", "QtObject {"]
    for key, value in tokens["colors"].items():
        lines.append(f'    readonly property color {key}: {json.dumps(value)}')
    for key, value in tokens["metrics"].items():
        lines.append(f"    readonly property int {key}: {value}")
    for key, value in tokens["font"].items():
        kind = "string" if isinstance(value, str) else "int"
        name = "font" + key[0].upper() + key[1:]
        lines.append(f"    readonly property {kind} {name}: {json.dumps(value)}")
    lines.append("}\n")
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "qml/Theme.qml"
    source = generate()
    if args.check:
        if not path.exists() or path.read_text() != source:
            raise SystemExit("Theme.qml differs from the reviewed token snapshot")
        print("Theme.qml matches design/tokens.json")
    else:
        path.write_text(source)
